-- Linea de venta (docs/DOMAIN_MODEL.md, seccion 2.16; RF-017, RF-020).
-- Inmutable una vez creada - unit_price es el precio efectivamente cobrado,
-- copiado de Price al confirmar, no cambia si el precio de referencia
-- cambia despues.
CREATE TABLE sale_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id BIGINT NOT NULL REFERENCES sale(id) ON DELETE RESTRICT,
    product_id BIGINT NOT NULL REFERENCES product(id) ON DELETE RESTRICT,
    unit_of_measure_id BIGINT NOT NULL REFERENCES unit_of_measure(id) ON DELETE RESTRICT,
    quantity NUMERIC(19,6) NOT NULL,
    unit_price NUMERIC(19,4) NOT NULL,
    discount_percentage NUMERIC(5,2) NOT NULL DEFAULT 0,
    line_total NUMERIC(19,4) NOT NULL,
    CONSTRAINT uq_sale_item_product UNIQUE (sale_id, product_id),
    CONSTRAINT chk_sale_item_quantity_positive CHECK (quantity > 0),
    CONSTRAINT chk_sale_item_unit_price_positive CHECK (unit_price > 0),
    CONSTRAINT chk_sale_item_discount_range CHECK (discount_percentage >= 0 AND discount_percentage <= 100),
    CONSTRAINT chk_sale_item_line_total_non_negative CHECK (line_total >= 0)
);
