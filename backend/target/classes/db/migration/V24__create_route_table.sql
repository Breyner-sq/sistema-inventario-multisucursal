-- Ruta entre dos sucursales (docs/DOMAIN_MODEL.md, seccion 2.17; RF-028).
-- Es un catalogo reutilizable, no un dato por transferencia: la clasificacion
-- se define una vez por par origen-destino y todas las transferencias de ese
-- par la heredan. Por eso UNIQUE (origin, destination) - ese par ES la
-- identidad de negocio de la ruta.
--
-- Decision de alcance (docs/DOMAIN_MODEL.md 2.17 dejaba ambas opciones
-- abiertas): "classification" es UNA etiqueta, no un conjunto. RF-028 pide
-- clasificar "por al menos uno de los tres criterios"; un conjunto de
-- etiquetas exigiria una tabla puente que ningun requisito justifica hoy.
--
-- Los datos de envio (transportista, fecha estimada, fecha real) NO viven
-- aqui: docs/DOMAIN_MODEL.md 2.17 decidio explicitamente modelarlos en
-- Transfer y no crear una entidad Shipment aparte. Route solo clasifica.
CREATE TABLE route (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    origin_branch_id BIGINT NOT NULL REFERENCES branch(id) ON DELETE RESTRICT,
    destination_branch_id BIGINT NOT NULL REFERENCES branch(id) ON DELETE RESTRICT,
    classification VARCHAR(20) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by VARCHAR(100),
    updated_by VARCHAR(100),
    CONSTRAINT uq_route_origin_destination UNIQUE (origin_branch_id, destination_branch_id),
    CONSTRAINT chk_route_origin_not_destination CHECK (origin_branch_id <> destination_branch_id),
    CONSTRAINT chk_route_classification CHECK (classification IN ('PRIORITY', 'COST', 'TIME'))
);
