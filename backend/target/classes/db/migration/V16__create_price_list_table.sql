-- nulo = lista global. Sin created_at/updated_at: el contrato aprobado
-- (docs/API_DESIGN.md, seccion 7.8) solo define GET/POST, sin edicion.
CREATE TABLE price_list (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    branch_id BIGINT REFERENCES branch(id) ON DELETE RESTRICT,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_price_list_name_branch UNIQUE (name, branch_id)
);
