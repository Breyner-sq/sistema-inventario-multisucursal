-- Transferencia entre sucursales (docs/DOMAIN_MODEL.md, seccion 2.18;
-- RF-022 a RF-026). Maquina de estados aprobada (seccion 4 del mismo
-- documento): REQUESTED -> APPROVED -> IN_TRANSIT -> RECEIVED_COMPLETE, o
-- -> RECEIVED_PARTIAL -> CLOSED, o REQUESTED -> REJECTED.
--
-- client_reference_id: clave de idempotencia para la solicitud (flujo C1 es
-- categoria 2 - creacion repetible, docs/CRITICAL_FLOWS.md seccion 1.1).
-- docs/DOMAIN_MODEL.md no listaba esta columna; se agrega siguiendo el mismo
-- patron ya aprobado y aplicado en Sale.client_reference_id (ver BR-032).
--
-- route_id (docs/DOMAIN_MODEL.md, 2.18) NO se incluye todavia: la entidad
-- Route pertenece al modulo `logistics`, fuera del alcance de esta fase
-- ("No implementes logistica avanzada"). Se agregara junto con esa tabla,
-- igual que sale_item_id se agrego a inventory_movement al implementar sales.
CREATE TABLE transfer (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transfer_number VARCHAR(30) NOT NULL UNIQUE,
    origin_branch_id BIGINT NOT NULL REFERENCES branch(id) ON DELETE RESTRICT,
    destination_branch_id BIGINT NOT NULL REFERENCES branch(id) ON DELETE RESTRICT,
    status VARCHAR(20) NOT NULL,
    urgency BOOLEAN NOT NULL DEFAULT FALSE,
    carrier_name VARCHAR(150),
    estimated_arrival_date DATE,
    requested_by_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    approved_by_user_id BIGINT REFERENCES users(id) ON DELETE RESTRICT,
    requested_at TIMESTAMPTZ NOT NULL,
    approved_at TIMESTAMPTZ,
    dispatched_at TIMESTAMPTZ,
    received_at TIMESTAMPTZ,
    client_reference_id VARCHAR(150) UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT chk_transfer_status CHECK (status IN
        ('REQUESTED', 'APPROVED', 'REJECTED', 'IN_TRANSIT', 'RECEIVED_COMPLETE', 'RECEIVED_PARTIAL', 'CLOSED')),
    CONSTRAINT chk_transfer_origin_not_destination CHECK (origin_branch_id <> destination_branch_id)
);

CREATE INDEX idx_transfer_origin ON transfer (origin_branch_id);
CREATE INDEX idx_transfer_destination ON transfer (destination_branch_id);
CREATE INDEX idx_transfer_status ON transfer (status);
