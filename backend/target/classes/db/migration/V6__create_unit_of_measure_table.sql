-- Catalogo de unidades de medida (docs/DOMAIN_MODEL.md, seccion 2.4; RF-011).
-- Sin columnas de auditoria: no existe endpoint de actualizacion en el
-- contrato aprobado (docs/API_DESIGN.md, seccion 7.4 - solo GET y POST),
-- serian columnas sin uso real.
CREATE TABLE unit_of_measure (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(10) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL
);
