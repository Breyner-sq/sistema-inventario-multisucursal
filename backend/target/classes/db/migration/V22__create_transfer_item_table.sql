-- Linea de transferencia (docs/DOMAIN_MODEL.md, seccion 2.19; RF-022 a
-- RF-026). Las cantidades se pueblan progresivamente segun avanza el flujo:
-- requested (C1) -> approved (C2) -> shipped (D) -> received/missing (E/F1)
-- -> discrepancy_treatment (F2). Una columna nula significa "esa etapa
-- todavia no ocurrio", y esa nulidad es la guarda de idempotencia por linea
-- (categoria 1): recibir dos veces la misma linea falla porque
-- quantity_received ya no es NULL.
--
-- quantity_missing queda NULL cuando la recepcion fue completa (no 0), tal
-- como muestra el ejemplo 9.6 de docs/API_DESIGN.md - resuelve la ambiguedad
-- que BR-008 dejaba abierta ("NULL o 0").
CREATE TABLE transfer_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transfer_id BIGINT NOT NULL REFERENCES transfer(id) ON DELETE RESTRICT,
    product_id BIGINT NOT NULL REFERENCES product(id) ON DELETE RESTRICT,
    unit_of_measure_id BIGINT NOT NULL REFERENCES unit_of_measure(id) ON DELETE RESTRICT,
    quantity_requested NUMERIC(19,6) NOT NULL,
    quantity_approved NUMERIC(19,6),
    quantity_shipped NUMERIC(19,6),
    quantity_received NUMERIC(19,6),
    quantity_missing NUMERIC(19,6),
    discrepancy_treatment VARCHAR(20),
    treatment_by_user_id BIGINT REFERENCES users(id) ON DELETE RESTRICT,
    treatment_at TIMESTAMPTZ,
    follow_up_transfer_id BIGINT REFERENCES transfer(id) ON DELETE RESTRICT,
    CONSTRAINT uq_transfer_item_product UNIQUE (transfer_id, product_id),
    CONSTRAINT chk_transfer_item_quantity_requested_positive CHECK (quantity_requested > 0),
    CONSTRAINT chk_transfer_item_quantity_approved_range CHECK (quantity_approved IS NULL OR (quantity_approved > 0 AND quantity_approved <= quantity_requested)),
    CONSTRAINT chk_transfer_item_quantity_shipped_range CHECK (quantity_shipped IS NULL OR (quantity_shipped > 0 AND quantity_shipped <= quantity_approved)),
    CONSTRAINT chk_transfer_item_quantity_received_range CHECK (quantity_received IS NULL OR (quantity_received >= 0 AND quantity_received <= quantity_shipped)),
    CONSTRAINT chk_transfer_item_quantity_missing CHECK (quantity_missing IS NULL OR quantity_missing = quantity_shipped - quantity_received),
    CONSTRAINT chk_transfer_item_treatment CHECK (discrepancy_treatment IS NULL OR discrepancy_treatment IN ('REENVIO', 'AJUSTE', 'RECLAMACION'))
);

CREATE INDEX idx_transfer_item_transfer ON transfer_item (transfer_id);
