-- Stock materializado por producto/sucursal (docs/DOMAIN_MODEL.md, seccion
-- 2.7). "version" es un contador manual controlado por la aplicacion (no la
-- anotacion @Version de JPA) para poder implementar exactamente el patron de
-- bloqueo optimista con reintento descrito en docs/CRITICAL_FLOWS.md, seccion
-- 1.2: UPDATE ... WHERE version = v, reintentar si 0 filas afectadas.
--
-- No tiene created_at/created_by/updated_by (a diferencia de las tablas que
-- extienden Auditable): docs/DOMAIN_MODEL.md solo lista "updated_at" para
-- esta entidad - es, por diseno, el unico dato mutable/sobrescribible del
-- subdominio (su historial vive en inventory_movement).
CREATE TABLE inventory (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES product(id) ON DELETE RESTRICT,
    branch_id BIGINT NOT NULL REFERENCES branch(id) ON DELETE RESTRICT,
    quantity_on_hand NUMERIC(19,6) NOT NULL DEFAULT 0,
    average_unit_cost NUMERIC(19,6) NOT NULL DEFAULT 0,
    minimum_stock NUMERIC(19,6) NOT NULL DEFAULT 0,
    version BIGINT NOT NULL DEFAULT 0,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_inventory_product_branch UNIQUE (product_id, branch_id),
    CONSTRAINT chk_inventory_quantity_non_negative CHECK (quantity_on_hand >= 0),
    CONSTRAINT chk_inventory_avg_cost_non_negative CHECK (average_unit_cost >= 0),
    CONSTRAINT chk_inventory_minimum_stock_non_negative CHECK (minimum_stock >= 0)
);
