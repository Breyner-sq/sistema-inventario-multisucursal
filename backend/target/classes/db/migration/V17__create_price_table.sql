CREATE TABLE price (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    price_list_id BIGINT NOT NULL REFERENCES price_list(id) ON DELETE RESTRICT,
    product_id BIGINT NOT NULL REFERENCES product(id) ON DELETE RESTRICT,
    unit_price NUMERIC(19,4) NOT NULL,
    valid_from TIMESTAMPTZ NOT NULL DEFAULT now(),
    valid_to TIMESTAMPTZ,
    CONSTRAINT chk_price_unit_price_positive CHECK (unit_price > 0)
);

CREATE UNIQUE INDEX uq_price_list_product_current ON price (price_list_id, product_id) WHERE valid_to IS NULL;
CREATE INDEX idx_price_list_product ON price (price_list_id, product_id);
