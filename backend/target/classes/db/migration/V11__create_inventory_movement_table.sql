-- Ledger append-only de movimientos de inventario (docs/DOMAIN_MODEL.md,
-- seccion 2.8; ADR-008; BR-001, BR-015, BR-021). Ninguna columna se
-- actualiza ni se elimina despues de insertada - la aplicacion no expone
-- ningun UPDATE/DELETE sobre esta tabla.
--
-- Las FK opcionales hacia documentos comerciales (purchase_order_item_id,
-- sale_item_id, transfer_item_id, docs/DOMAIN_MODEL.md seccion 2.8) todavia
-- no se agregan: esas tablas no existen en esta fase (compras/ventas/
-- transferencias, condicion de parada explicita). Se agregaran en la
-- migracion del modulo correspondiente cuando se implemente cada uno; hasta
-- entonces, todo movimiento de esta fase es un ajuste manual sin documento
-- de origen.
CREATE TABLE inventory_movement (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES product(id) ON DELETE RESTRICT,
    branch_id BIGINT NOT NULL REFERENCES branch(id) ON DELETE RESTRICT,
    direction VARCHAR(10) NOT NULL,
    reason VARCHAR(30) NOT NULL,
    quantity NUMERIC(19,6) NOT NULL,
    unit_of_measure_id BIGINT NOT NULL REFERENCES unit_of_measure(id) ON DELETE RESTRICT,
    responsible_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    occurred_at TIMESTAMPTZ NOT NULL,
    notes VARCHAR(1000),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT chk_inventory_movement_direction CHECK (direction IN ('INGRESO', 'RETIRO')),
    CONSTRAINT chk_inventory_movement_reason CHECK (reason IN
        ('COMPRA', 'DEVOLUCION', 'AJUSTE_INGRESO', 'VENTA', 'MERMA', 'AJUSTE_RETIRO', 'TRANSFERENCIA_SALIDA', 'TRANSFERENCIA_ENTRADA')),
    CONSTRAINT chk_inventory_movement_quantity_positive CHECK (quantity > 0)
);

CREATE INDEX idx_inventory_movement_product_branch ON inventory_movement (product_id, branch_id);
CREATE INDEX idx_inventory_movement_occurred_at ON inventory_movement (occurred_at DESC);
