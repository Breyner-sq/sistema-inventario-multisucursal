-- Linea de orden de compra (docs/DOMAIN_MODEL.md, seccion 2.12; RF-013,
-- RF-014, RF-016). "version" resuelve la decision pendiente #4 de
-- docs/BUSINESS_RULES.md ("Ajustes pendientes al modelo de dominio"):
-- necesaria porque quantity_received puede incrementarse en varias
-- recepciones parciales concurrentes sobre la misma linea
-- (docs/CRITICAL_FLOWS.md, flujo B) - mismo patron manual de bloqueo
-- optimista que inventory.version (V10), no @Version de JPA.
--
-- unit_price/discount_percentage/line_total son historicos e inmutables una
-- vez creada la linea (condicion pactada al ordenar, docs/DOMAIN_MODEL.md
-- 2.12) - distintos del "unitPrice" que se envia en cada recepcion
-- (docs/openapi.yaml PurchaseReceiptRequest), que es el costo efectivamente
-- recibido usado solo para recalcular Inventory.average_unit_cost (BR-004).
CREATE TABLE purchase_order_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_order_id BIGINT NOT NULL REFERENCES purchase_order(id) ON DELETE RESTRICT,
    product_id BIGINT NOT NULL REFERENCES product(id) ON DELETE RESTRICT,
    unit_of_measure_id BIGINT NOT NULL REFERENCES unit_of_measure(id) ON DELETE RESTRICT,
    quantity_ordered NUMERIC(19,6) NOT NULL,
    quantity_received NUMERIC(19,6) NOT NULL DEFAULT 0,
    unit_price NUMERIC(19,4) NOT NULL,
    discount_percentage NUMERIC(5,2) NOT NULL DEFAULT 0,
    line_total NUMERIC(19,4) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uq_purchase_order_item_product UNIQUE (purchase_order_id, product_id),
    CONSTRAINT chk_purchase_order_item_quantity_ordered_positive CHECK (quantity_ordered > 0),
    CONSTRAINT chk_purchase_order_item_quantity_received_range CHECK (quantity_received >= 0 AND quantity_received <= quantity_ordered),
    CONSTRAINT chk_purchase_order_item_unit_price_positive CHECK (unit_price > 0),
    CONSTRAINT chk_purchase_order_item_discount_range CHECK (discount_percentage >= 0 AND discount_percentage <= 100),
    CONSTRAINT chk_purchase_order_item_line_total_non_negative CHECK (line_total >= 0)
);
